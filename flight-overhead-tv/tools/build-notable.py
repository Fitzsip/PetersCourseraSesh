#!/usr/bin/env python3
"""
Builds js/notable.js from plane-alert-db (https://github.com/sdr-enthusiasts/plane-alert-db).

    git clone --depth 1 https://github.com/sdr-enthusiasts/plane-alert-db.git /tmp/pad
    python3 tools/build-notable.py /tmp/pad/plane-alert-db.csv

Keeps aircraft associated with well-known people (alerted like private jets) and
service aircraft such as coast guard, air ambulance and police (named, not alerted).
The database's humorous tags are not copied.
"""
import csv
import json
import os
import re
import sys

# plane-alert-db category -> (kind, label shown in the app)
PEOPLE = {
    "Don't you know who I am?": "Celebrity",
    "Oligarch": "Billionaire",
    "Football": "Sports",
    "Royal Aircraft": "Royal",
    "Head of State": "Head of state",
}
SERVICES = {
    "Coastguard": "Coast guard",
    "Flying Doctors": "Air ambulance",
    "Police Forces": "Police",
    "UK National Police Air Service": "Police",
}
# Companies the database lists as owner, with the person it names for them (checked by hand).
# Every other aircraft shows its operator; the database's tags are often jokes and are never used.
FRONT_COMPANIES = {
    "Falcon Aviation Holdings": "Elon Musk",
    "Falcon Landing LLC": "Elon Musk",
    "Reliance Commercial Dealers Ltd": "Mukesh Ambani",
    "Green Chair Productions Inc": "Dr Phil",
    "Firefly Entertainment Inc": "Taylor Swift",
    "Island Jet Inc": "Taylor Swift",
    "ETPC Aviation": "Tyler Perry",
    "Constellation Productions": "John Travolta",
    "Wings of Grace": "Folorunso Alakija",
    "Greensill Capital": "Lex Greensill",
}


def person(row):
    """The person or organisation an aircraft is associated with."""
    operator = row["$Operator"].strip()
    return FRONT_COMPANIES.get(operator, operator)


def main(path):
    out = {}
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            hex_id = row["$ICAO"].strip().lower()
            category = row["Category"].strip()
            if not re.fullmatch(r"[0-9a-f]{6}", hex_id):
                continue
            if category in PEOPLE:
                out[hex_id] = [person(row), PEOPLE[category], 1]
            elif category in SERVICES:
                out[hex_id] = [row["$Operator"].strip(), SERVICES[category], 0]

    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "notable.js")
    people = sum(1 for v in out.values() if v[2])
    with open(target, "w", encoding="utf-8") as f:
        f.write("/*\n"
                " * Aircraft associated with well-known people, plus coast guard, air ambulance and police\n"
                " * aircraft, keyed by ICAO hex: [name, label, alert (1) or name only (0)].\n"
                " * Generated by tools/build-notable.py from plane-alert-db\n"
                " * (https://github.com/sdr-enthusiasts/plane-alert-db), (c) SDR-Enthusiasts and\n"
                " * contributors, made available under the Open Database License (ODbL 1.0):\n"
                " * http://opendatacommons.org/licenses/odbl/1.0/. This extract is also under the ODbL.\n"
                " */\n")
        f.write("var NOTABLE = ")
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
        f.write(";\n")
        # The app refreshes the list from plane-alert-db itself (js/notable-live.js) with these rules.
        f.write("var NOTABLE_RULES = ")
        json.dump({"people": PEOPLE, "services": SERVICES, "fronts": FRONT_COMPANIES}, f,
                  ensure_ascii=False, separators=(",", ":"), sort_keys=True)
        f.write(";\n")
    print(f"Wrote {len(out)} aircraft ({people} associated with people) to js/notable.js")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
